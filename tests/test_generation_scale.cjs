const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context={window:{}};vm.createContext(context);
vm.runInContext(fs.readFileSync('web/generation-scale.js','utf8'),context);
const {rows,visible}=context.window.GenealogyGenerations;
const model={nodes:{child:{x:400,y:904,w:200,h:312},mother:{x:100,y:484,w:200,h:312},father:{x:700,y:484,w:200,h:312},grandparent:{x:700,y:64,w:200,h:312}},ranks:{child:-1,mother:0,father:0,grandparent:1}};
const original=JSON.stringify(model),levels=rows(model);
assert.equal(levels.length,3,'One marker per existing rank, including partial ancestry');
assert.deepEqual(Array.from(levels,row=>row.number),[1,2,3]);
assert.deepEqual(Array.from(levels,row=>row.y),[220,640,1060]);
assert(levels.every(row=>row.total===3));
const initial=visible(levels,{scale:.5,y:0,height:1000});
const panned=visible(levels,{scale:.5,y:-150,height:1000,x:5000});
assert.deepEqual(Array.from(panned,row=>row.number),[2,3],'Hidden oldest row must not renumber the remaining rows');
for(const row of panned)assert.equal(row.screenY,initial.find(other=>other.number===row.number).screenY-150);
assert.equal(visible(levels,{scale:1,y:0,height:1000})[1].screenY,640,'Zoom follows the actual row center');
assert.equal(visible(levels,{scale:.08,y:40,height:500}).length,3,'Minimum overview scale keeps normal rows legible');
const dense=Array.from({length:40},(_,i)=>({number:i+1,total:40,y:i*420}));
const thinned=visible(dense,{scale:.01,y:40,height:500});
for(let i=1;i<thinned.length;i++)assert(thinned[i].screenY-thinned[i-1].screenY>=32,'Small scale labels do not overlap');
const moved=visible(dense,{scale:.01,y:-30,height:500});
for(const row of moved)assert.equal((row.number-1)%8,0,'Thinning uses global generation numbers rather than visible indices');
const edge=visible(dense.slice(0,7),{scale:.01,y:15,height:70});
assert.deepEqual(Array.from(edge,row=>row.number),[7],'A visible youngest row still has its own label when other ticks are clipped');
const single=rows({nodes:{only:{y:64,h:312}},ranks:{only:0}});
assert.equal(single[0].number,1);assert.equal(single[0].total,1);
assert.equal(visible(single,{scale:1,y:0,height:400})[0].screenY,220);
assert.equal(rows({nodes:{},ranks:{}}).length,0);
assert.equal(visible(levels,{scale:0,y:0,height:500}).length,0);
const sparse=rows({nodes:{old:{y:64,h:312},young:{y:904,h:312}},ranks:{old:2,young:0}});
assert.deepEqual(Array.from(sparse,row=>row.number),[1,3],'Missing rows are not invented or compacted');
model.nodes.father.x+=300;
assert.equal(JSON.stringify(rows(model)),JSON.stringify(levels),'Horizontal personal placement does not change generation labels');
model.nodes.father.x-=300;assert.equal(JSON.stringify(model),original,'The ruler never mutates tree data or layout');
console.log('Generation scale: existing ranks, stable numbering, single/uneven trees, pan/zoom, overview thinning and unchanged layout verified.');
